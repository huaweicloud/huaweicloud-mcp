@mcp.tool()
@guard(risk=ToolRisk.READ)
async def list_all_resources(
    region_id: str | None = None,
    ep_id: str | None = None,
    resource_type: str | None = None,
    limit: int | None = None,
    marker: str | None = None,
    resource_id: str | None = None,
    group_id: str | None = None,
    name: str | None = None,
    tags: list[str] | None = None,
) -> dict[str, Any]:
    """List all resources across services, with optional filters.

    Scenario: user wants an inventory of all resources under the account,
    optionally filtered by region, enterprise project, resource type
    (provider.type), resource group, name or tags.

    Args:
        region_id: filter by region, e.g. ``cn-north-4``.
        ep_id: filter by enterprise project ID.
        resource_type: filter by resource type in ``provider.type`` form,
            e.g. ``ecs.cloudservers``.
        limit: max resources per page, 1-100; when omitted the API default
            is used.
        marker: pagination marker returned by a previous call.
        resource_id: filter by exact resource ID.
        group_id: filter by resource group ID.
        name: filter by resource name substring.
        tags: filter by tags, ``key`` or ``key=value`` (max 5).

    Returns:
        Paginated envelope with items (id, name, provider, type, region_id,
        project_id, ep_id, group_id, created, updated, tags, state).
    """
    return await ResourceService().list_all_resources(
        region_id=region_id,
        ep_id=ep_id,
        resource_type=resource_type,
        limit=limit,
        marker=marker,
        id_=resource_id,
        group_id=group_id,
        name=name,
        tags=tags,
    )


