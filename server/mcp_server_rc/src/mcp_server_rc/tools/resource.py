"""Tools layer: scenario tools for RC (Resource Center)."""

from __future__ import annotations

from typing import Any

from huaweicloud_mcp_core.security import ToolRisk, guard

from mcp_server_rc.server import mcp
from mcp_server_rc.service.resource_service import ResourceService


@mcp.tool()
@guard(risk=ToolRisk.READ)
async def run_query(
    expression: str,
    limit: int = 50,
) -> dict[str, Any]:
    """Execute a ResourceQL query and return the matching resources.

    Scenario: user wants to query their Huawei Cloud resources using the
    ResourceQL expression language (e.g. generated by the nl-to-resourceql
    skill). The tool sends the expression to the RC API and returns the
    matching resources.

    Args:
        expression: a valid ResourceQL expression string, e.g.
            ``SELECT * FROM resources WHERE provider = 'ecs' LIMIT 10``.
        limit: max results to return, 1-100 (default 50).

    Returns:
        Paginated envelope with the query results. Items keep the fields
        selected by the expression (including ``AS`` aliases); null values
        are dropped.
    """
    return await ResourceService().run_query(expression=expression, limit=limit)


